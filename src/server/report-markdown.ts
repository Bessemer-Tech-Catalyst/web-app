/** Mirrors `lib/report-join.ts`; duplicated only as a predicate to stay dependency-free. */
const matches = (testId: string, scenarioId: string) =>
  testId === scenarioId || testId === `t-${scenarioId}` || testId === `q-${scenarioId}`;

function findResult(report: TestQualityReport, scenarioId: string) {
  let found;
  for (const r of report.results) if (matches(r.testId, scenarioId)) found = r;
  return found;
}

/** A pipe in a cell ends the cell. Newlines end the row. */
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();

function fmtDuration(ms: number): string {
  const s = Math.round(ms / 1000);
  return s < 60 ? `${s}s` : `${Math.floor(s / 60)}m ${String(s % 60).padStart(2, "0")}s`;
}

const fmtUsd = (n: number) => `$${n.toFixed(n < 1 ? 3 : 2)}`;

const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;
